-- 1. USERS: Identity, roles and account status
CREATE TABLE users (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(255) NOT NULL UNIQUE,
  password_hash VARCHAR2(255) DEFAULT 'demo123' NOT NULL,
  role VARCHAR2(50) NOT NULL,
  name VARCHAR2(120) NOT NULL,
  phone VARCHAR2(25),
  department VARCHAR2(120),
  status VARCHAR2(30) DEFAULT 'Active' NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT chk_user_role CHECK (role IN ('citizen', 'authority', 'staff', 'admin')),
  CONSTRAINT chk_user_status CHECK (status IN ('Active', 'Suspended', 'Inactive'))
);

-- 2. CITIZEN_PROFILES: Granular citizen demographic & preferred locality
CREATE TABLE citizen_profiles (
  profile_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_email VARCHAR2(255) NOT NULL UNIQUE,
  full_name VARCHAR2(120) NOT NULL,
  phone VARCHAR2(25),
  address VARCHAR2(500),
  locality VARCHAR2(100),
  landmark VARCHAR2(200),
  preferred_notifications VARCHAR2(100) DEFAULT 'email,sms' NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_citizen_email FOREIGN KEY (user_email) REFERENCES users(email) ON DELETE CASCADE
);

-- 3. DEPARTMENTS: Municipal departments and SLA commitments
CREATE TABLE city_departments (
  department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(120) NOT NULL UNIQUE,
  description VARCHAR2(500),
  head_officer VARCHAR2(120),
  contact_email VARCHAR2(255),
  phone VARCHAR2(30),
  active_cases NUMBER DEFAULT 0,
  sla_hours NUMBER DEFAULT 48,
  status VARCHAR2(30) DEFAULT 'Active' NOT NULL,
  categories_handled VARCHAR2(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT chk_dept_status CHECK (status IN ('Active', 'Inactive'))
);

-- 4. COMPLAINTS: Central Grievance Register
CREATE TABLE city_complaints (
  complaint_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_code VARCHAR2(35) NOT NULL UNIQUE,
  citizen_name VARCHAR2(120) NOT NULL,
  citizen_email VARCHAR2(255) NOT NULL,
  phone VARCHAR2(25),
  category VARCHAR2(100) NOT NULL,
  title VARCHAR2(200) NOT NULL,
  description VARCHAR2(2000) NOT NULL,
  area VARCHAR2(100) NOT NULL,
  address VARCHAR2(500) NOT NULL,
  landmark VARCHAR2(200),
  latitude NUMBER(9,6),
  longitude NUMBER(9,6),
  photo_url VARCHAR2(600),
  severity VARCHAR2(30) DEFAULT 'Medium' NOT NULL,
  safety_risk NUMBER(1) DEFAULT 0 NOT NULL,
  department VARCHAR2(120) NOT NULL,
  priority VARCHAR2(30) DEFAULT 'Medium' NOT NULL,
  status VARCHAR2(30) DEFAULT 'Open' NOT NULL,
  assigned_to VARCHAR2(120) DEFAULT 'Unassigned',
  resolution VARCHAR2(1500),
  resolution_photo VARCHAR2(600),
  expected_resolution_date VARCHAR2(30),
  reopened_count NUMBER DEFAULT 0,
  reopen_reason VARCHAR2(1000),
  withdrawal_reason VARCHAR2(500),
  is_draft NUMBER(1) DEFAULT 0 NOT NULL,
  history_json CLOB,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT chk_comp_priority CHECK (priority IN ('Low', 'Medium', 'High', 'Critical')),
  CONSTRAINT chk_comp_status CHECK (status IN ('Draft', 'Open', 'Submitted', 'Under Review', 'Assigned', 'In Progress', 'Resolved', 'Reopened', 'Withdrawn', 'Closed'))
);

-- Performance Indexes on Complaints
CREATE INDEX idx_comp_email ON city_complaints(citizen_email);
CREATE INDEX idx_comp_status ON city_complaints(status);
CREATE INDEX idx_comp_dept ON city_complaints(department);
CREATE INDEX idx_comp_created ON city_complaints(created_at);

