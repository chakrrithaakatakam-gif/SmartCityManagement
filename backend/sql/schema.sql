-- Compatibility view for queries on complaints
CREATE OR REPLACE VIEW complaints AS
SELECT 
  complaint_id AS db_id,
  reference_code AS id,
  citizen_name AS citizen,
  citizen_email AS email,
  phone,
  category,
  title,
  description,
  area,
  address,
  landmark,
  latitude,
  longitude,
  photo_url,
  severity,
  safety_risk,
  department,
  priority,
  status,
  assigned_to AS "assignedTo",
  resolution,
  resolution_photo,
  expected_resolution_date,
  reopened_count,
  reopen_reason,
  withdrawal_reason,
  is_draft,
  created_at AS "createdAt",
  updated_at AS "updatedAt"
FROM city_complaints;

-- Active Unresolved Complaints View
CREATE OR REPLACE VIEW unresolved_complaints_view AS
SELECT reference_code, title, category, department, priority, status, created_at
FROM city_complaints
WHERE status NOT IN ('Resolved', 'Closed', 'Withdrawn', 'Draft');

-- Departmental Workload & Performance View
CREATE OR REPLACE VIEW department_performance_view AS
SELECT 
  d.name AS department_name,
  d.head_officer,
  COUNT(c.complaint_id) AS total_complaints,
  SUM(CASE WHEN c.status IN ('Resolved', 'Closed') THEN 1 ELSE 0 END) AS resolved_complaints,
  SUM(CASE WHEN c.status NOT IN ('Resolved', 'Closed', 'Withdrawn', 'Draft') THEN 1 ELSE 0 END) AS pending_complaints,
  d.sla_hours
FROM city_departments d
LEFT JOIN city_complaints c ON c.department = d.name
GROUP BY d.department_id, d.name, d.head_officer, d.sla_hours;

-- Financial Budget Utilization View
CREATE OR REPLACE VIEW budget_overview_view AS
SELECT 
  b.financial_year,
  b.department,
  b.project_name,
  b.allocated_amount,
  b.spent_amount,
  b.remaining_amount,
  ROUND((b.spent_amount / b.allocated_amount) * 100, 1) AS utilization_pct
FROM budgets b;

